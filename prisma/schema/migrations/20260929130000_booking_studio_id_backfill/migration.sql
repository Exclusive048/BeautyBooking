-- 29.09 доработки · 08 (BOOKING-SCOPE-OR-COLLAPSE, инв. #45) — `Booking.studioId`
-- выравнивается с поверхностью записи.
--
-- Схему миграция не меняет — только данные. С этой версии списки студии
-- (журнал, календарь, KPI, клиенты, аналитика, удаление кабинета, уход мастера)
-- берут записи ТОЛЬКО по `studioId` (`src/lib/studio/booking-scope.ts`), как и
-- право на действие (`studio/tenancy.ts`). Прежний `OR` добавлял записи по
-- `providerId` студии, поэтому строка с пустым `studioId` была видна, но
-- неуправляема (SMOKE-01 · F1); после свёртки такая строка пропала бы из
-- журнала молча. Значение — то же, что выводит единственный writer
-- `createBookingRow` (FIX-C1): студия, чей `providerId` совпадает с `providerId`
-- записи.
--
-- Чинит классы (а) «поверхность студии, `studioId` пуст» и (б) «поверхность
-- студии, `studioId` чужой студии». Класс (в) «поверхность мастера, `studioId`
-- задан» НЕ трогается — это решение владельца по списку (DEPLOY-BACKLOG).
-- Идемпотентна: повторный прогон находит ноль строк. На dev 2026-09-29 —
-- 5 сидовых строк класса (а) от 2026-08-03 (до FIX-C1); на проде ожидаемо 0.
-- Дрейф после неё сторожит `deploy:post` (`reportBookingStudioScopeDrift`).
UPDATE "Booking" b
SET "studioId" = s."id"
FROM "Studio" s
WHERE s."providerId" = b."providerId"
  AND b."studioId" IS DISTINCT FROM s."id";
