/**
 * SKILL-TZ-01 · паттерны распознавания для `check:tz`.
 *
 * Вынесены из `check-tz.mjs` (LOGIC-29), чтобы их можно было проверить тестом:
 * сам скрипт при импорте обходит дерево, печатает отчёт и зовёт `process.exit`,
 * то есть импортировать его из теста нельзя. А проверять эти регулярки надо
 * именно тестом — находка LOGIC-29 в том и состояла, что одна из них молча
 * ошибалась в течение долгого времени.
 */

/** Рендеры времени: кандидаты всегда (без явной зоны это viewer-/host-tz). */
export const TIME_SPECIFIC_RE =
  /\.toLocaleTimeString\s*\(|new\s+Intl\.DateTimeFormat\s*\(|\.getHours\s*\(\)|\.getMinutes\s*\(\)|\.getUTCHours\s*\(\)|\.getUTCMinutes\s*\(\)/;

/**
 * Неоднозначные рендеры: `.toLocaleString`/`.toLocaleDateString` форматируют и
 * ЧИСЛА (`count.toLocaleString("ru-RU")`), поэтому сами по себе кандидатами не
 * считаются — нужен ключ даты/времени рядом.
 */
export const AMBIGUOUS_RE = /\.toLocaleString\s*\(|\.toLocaleDateString\s*\(/;

export const DATETIME_OPT_RE =
  /\b(hour|minute|second|weekday|day|month|year|dateStyle|timeStyle|timeZoneName|era)\b\s*:/;

/** Явный опт-аут намерения: `// tz-ok: viewer`. */
export const OPTOUT_RE = /\/\/\s*tz-ok\b/i;

/**
 * LOGIC-29 — «зона задана явно, это не кандидат».
 *
 * Здесь стояло `/timeZone\s*:/` — с ОБЯЗАТЕЛЬНЫМ двоеточием, поэтому
 * ES6-шорткат `{ timeZone }` не распознавался и корректный код репортился как
 * подозрительный. Пять ложных срабатываний на живых salon-tz поверхностях;
 * инструмент, который стабильно указывает на исправное, перестают читать — и
 * тогда он пропускает настоящее.
 *
 * Границы подобраны так, чтобы шорткат распознавался, но глушилка не стала
 * шире нужного:
 *   • `\b` не даёт совпасть внутри `timeZoneName` — это ДРУГАЯ опция Intl, она
 *     печатает название зоны, а не задаёт её, и код с ней остаётся кандидатом;
 *   • разделитель после имени (`,` или `}`) — и есть форма шортката;
 *     `const timeZone = …` под неё не подходит, то есть объявление переменной
 *     находку не глушит.
 */
export const TZ_AWARE_RE = /\btimeZone\s*[:,}]/;
