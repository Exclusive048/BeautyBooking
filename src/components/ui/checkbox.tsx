import React from "react";
import { cn } from "@/lib/cn";

/**
 * UI-15 — единственный чекбокс проекта.
 *
 * До него `type="checkbox"` жил в 13 местах в четырёх оформлениях, и худшее
 * стояло там, где цена ошибки максимальна: подтверждение необратимого удаления
 * аккаунта (`DeleteAccountModal`) было СЫРЫМ чекбоксом браузера
 * (`className="mt-1"`), то есть с `accent-color: auto` — системной синей
 * галочкой вместо бордовой бренд-заливки.
 *
 * 🔴 Три из четырёх «оформлений» расходились МЁРТВЫМИ классами. У поля с
 * `appearance: auto` браузер рисует контрол сам и авторские `border-*`,
 * `bg-*` и `rounded` до пикселей не доходят вовсе — проверено подстановкой
 * `background:#ff0000` + `border:3px solid #00ff00` прямо в рантайме: картинка
 * не изменилась ни на пиксель, а `getComputedStyle` при этом отдаёт
 * `border-width: 0px`. Поэтому «самый полный» прежний вариант
 * (`legal-consent-group`: `rounded border border-border-subtle bg-bg-card`) на
 * деле не отличался от варианта вообще без них, и копирование его дословно
 * разнесло бы по всем сайтам классы, которые ничего не делают, — ровно тот
 * класс дефекта, что UI-01…UI-08 вычищали из разметки.
 *
 * До пикселей доходят ровно четыре вещи, и компонент состоит из них:
 * размер, `accent-color` (заливка и галочка отмеченного состояния),
 * `box-shadow` кольца фокуса и `opacity` для выключенного.
 *
 * Про фокус отдельно: базовый слой `globals.css` гасит `outline` у ВСЕХ полей
 * (`input:focus { outline: none }`), поэтому системного кольца у чекбокса нет
 * ни при каких условиях — остаётся только базовый `box-shadow` (альфа 0.22).
 * Кольцо `ring-primary/40` возвращает чекбоксу тот же индикатор, что несут
 * остальные управляющие элементы проекта.
 *
 * Компонент — это САМО поле, без обёртки-метки: у 13 сайтов разные раскладки
 * (строка списка с ценой справа, абзац согласия со ссылками, плотный тулбар),
 * и общая обёртка заставила бы их перестраивать разметку, то есть менять
 * внешний вид ради унификации контрола.
 */

type CheckboxSize = "sm" | "md";

/**
 * `type` закрыт намеренно — иначе общий чекбокс можно превратить в радио или
 * текстовое поле, и guard, который ищет сырой `type="checkbox"`, это пропустит.
 * `size` у `InputHTMLAttributes` — числовой атрибут текстового поля; к чекбоксу
 * он неприменим, и имя переиспользовано под шкалу размеров, как в `Switch`.
 */
type Props = Omit<React.InputHTMLAttributes<HTMLInputElement>, "type" | "size"> & {
  size?: CheckboxSize;
};

const SIZE_STYLES: Record<CheckboxSize, string> = {
  // `sm` существует ради двух плотных тулбаров (фильтр чатов, переключатель
  // сравнения в аналитике студии), которые и до унификации стояли на 14px.
  // Поднять их до 16px значило бы поменять раскладку строки, а не починить контрол.
  sm: "h-3.5 w-3.5",
  md: "h-4 w-4",
};

export function Checkbox({ size = "md", className, ...props }: Props) {
  return (
    <input
      type="checkbox"
      {...props}
      className={cn(
        "shrink-0 cursor-pointer accent-primary",
        "focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-primary/40",
        "disabled:cursor-not-allowed disabled:opacity-60",
        SIZE_STYLES[size],
        className,
      )}
    />
  );
}
