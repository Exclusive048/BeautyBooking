import { NextResponse } from "next/server";

import { checkReadiness, HEALTH_DEPENDENCY_TIMEOUT_MS } from "@/lib/health/probe";

export const runtime = "nodejs";
export const dynamic = "force-dynamic";

/**
 * FIX-C2 · SMOKE-01 · F2 — **readiness**: пригодны ли зависимости. Отвечает
 * ВСЕГДА и в пределах `HEALTH_DEPENDENCY_TIMEOUT_MS` на зависимость (проверки
 * идут параллельно, поэтому граница общая, а не суммарная).
 *
 * ## Кому это нужно и почему отдельным адресом
 *
 * `GET /api/health` после FIX-C2 — живость: он ничего не знает о зависимостях,
 * и по нему принимаются решения о МАРШРУТИЗАЦИИ (балансировщик, статус
 * контейнера, автооткат деплоя). Разбор этого решения — в шапке того файла.
 * Здесь живёт вторая половина, у которой другой потребитель и другая реакция:
 *
 *   - **дежурный по runbook'у** — ему нужен не вердикт, а РАЗЛИЧЕНИЕ: «Redis
 *     лежит, БД жива» и «лежит всё» требуют разных действий, и это единственная
 *     ценность пробы во время инцидента. Поэтому тело несёт состояние каждой
 *     зависимости отдельно, а не сведённый флаг;
 *   - **шаг деплоя** — `deploy.yml` после «контейнер жив» спрашивает ещё и
 *     «дошла ли эта сборка до БД», потому что живость не отличает рабочий образ
 *     от образа с неверным `DATABASE_URL` или неприменённой миграцией. 🔴
 *     Гейтом там служит **только `db`**: откат на `:previous` чинит плохую
 *     сборку, но не чинит лежащий Redis — на нём старый код так же нездоров,
 *     то есть откат по Redis был бы обрядом, а не средством.
 *
 * ## Состояний три, а не два
 *
 * `disabled` (нет `REDIS_URL` — легитимная dev-конфигурация с memory-fallback)
 * отличается от `down` (сконфигурирован и не отвечает). Слипшись, они послали бы
 * дежурного искать инцидент там, где стоит галочка в конфиге.
 *
 * HTTP-код при этом бинарен по необходимости — его читают автоматы: 200, когда
 * ни одна зависимость не `down`; 503 иначе. Подробность — в теле.
 *
 * ⚠️ Проба не должна усиливать brownout: обращения дешёвые (`SELECT 1` и `PING`),
 * ограничены сверху и не открывают новых соединений — оба клиента
 * переиспользуются (пул Prisma, кэшированный в `globalThis` клиент Redis).
 * Кэш ответа здесь намеренно НЕ заводится: интервал опроса задаёт потребитель
 * (compose — 30 с), а кэш во время инцидента показывал бы дежурному прошлое.
 */
export async function GET() {
  const report = await checkReadiness();
  const ready = report.db !== "down" && report.redis !== "down";

  return NextResponse.json(
    {
      ok: ready,
      status: ready ? "ready" : "degraded",
      dependencies: { db: report.db, redis: report.redis },
      checkedInMs: report.checkedInMs,
      timeoutMs: HEALTH_DEPENDENCY_TIMEOUT_MS,
      timestamp: new Date().toISOString(),
    },
    { status: ready ? 200 : 503, headers: { "Cache-Control": "no-store" } },
  );
}
