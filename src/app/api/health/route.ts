import { NextResponse } from "next/server";

export const runtime = "nodejs";
// Проба обязана отражать состояние ЭТОГО процесса сейчас, а не то, что Next
// счёл возможным закэшировать на этапе сборки.
export const dynamic = "force-dynamic";

/**
 * FIX-C2 · SMOKE-01 · F2 — **liveness**: способен ли процесс обслуживать запрос.
 * Ввода-вывода к зависимостям здесь нет вовсе. Готовность зависимостей —
 * `GET /api/health/ready`.
 *
 * ## Почему смысл эндпоинта изменён, а не только добавлен таймаут
 *
 * Дефект был в том, что проба висела (`client.ping()` без границы, разбор — в
 * `lib/health/probe.ts`). Но один таймаут починил бы симптом и оставил бы
 * причину, которая опаснее: **проба готовности была подключена к решениям о
 * живости**, а у этих вопросов разные правильные ответы.
 *
 * Прежний контракт — «200, только если Postgres И Redis доступны, иначе 503» —
 * читали два автомата:
 *
 *   - `docker-compose.prod.yml` (`healthcheck`, `timeout: 10s`, `retries: 3`);
 *   - `deploy.yml`, ждущий `State.Health.Status = healthy` и делающий
 *     **автооткат на `:previous`**, если за 180 с не дождался.
 *
 * Отсюда следствие, которое сам продукт объявляет неверным: обрыв Redis — это
 * **частичный** отказ by design (чувствительные роуты fail-closed, инв. #6), а
 * публичная витрина при этом продолжает работать (`docs/runbooks/redis-down.md`).
 * При старом контракте такой обрыв помечал контейнер нездоровым, то есть
 * балансировщик вывел бы из ротации единственный живой инстанс и превратил
 * ЧАСТИЧНУЮ деградацию в ПОЛНУЮ. А деплой, случившийся в это окно, откатился бы
 * на `:previous` — на код, который ничем не лучше, потому что сломан не код.
 *
 * Поэтому: маршрутизация и откат смотрят сюда (живость), человек и мониторинг —
 * в `/ready` (готовность). Путь оставлен прежним намеренно: конфигурация
 * балансировщика живёт вне репозитория (`docs/DEPLOYMENT-ARCHITECTURE.md` §1.7),
 * и смена смысла по тому же адресу не требует её трогать, тогда как переезд
 * пути потребовал бы — и до него проба молча указывала бы в никуда.
 *
 * ## Что эта проба ловит
 *
 * Процесс не слушает, событийный цикл заблокирован, приложение не поднялось,
 * контейнер мёртв — во всех этих случаях запрос не получит ответа, и потребитель
 * увидит отказ на своём таймауте. Это ровно то, на что балансировщику стоит
 * реагировать сменой маршрута. Всё остальное — «жив, но деградировал» — это
 * `/ready`, и реакция на него другая: алерт дежурному, а не переключение
 * трафика.
 *
 * ⚠️ Не добавлять сюда проверок зависимостей. Проба, которая обращается к тому,
 * о чьей аварии она сообщает, становится частью аварии — и именно это F2 и
 * измерил. Сторож — `api/health/health-probe-contract.test.ts`.
 */
export function GET() {
  return NextResponse.json(
    { ok: true, status: "live", timestamp: new Date().toISOString() },
    { status: 200, headers: { "Cache-Control": "no-store" } },
  );
}
