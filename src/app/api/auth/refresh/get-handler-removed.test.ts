import { describe, expect, it } from "vitest";

import * as refreshRoute from "./route";

/**
 * SEC-24 — GET-обработчик `/api/auth/refresh` ротировал сессию и редиректил на
 * `?next=`, то есть менял состояние по НАВИГАЦИИ. Межсайтовая top-level
 * навигация отправляет `SameSite=Lax`-куки, а CSRF-слой (SEC-08) гейтит только
 * мутирующие МЕТОДЫ и такой запрос пропускает; путь вдобавок исключён из
 * рейт-лимита (`proxy.ts:140` — намеренно, там же прокси сам зовёт refresh).
 * Потолок ущерба был «принудительная ротация чужой сессии», но форма ровно та,
 * от которой в проекте уже строятся защиты.
 *
 * Выбрано удаление, а не гейт: вызывающих у GET было ноль, а прозрачное
 * обновление сессии при навигации делает прокси — он зовёт **POST** этого же
 * роута. Тест сторожит возврат: обработчик легко восстановить из истории git.
 */
describe("SEC-24 · ротация сессии только на POST", () => {
  it("GET-обработчика нет", () => {
    expect("GET" in refreshRoute).toBe(false);
  });

  it("POST-обработчик на месте — прокси зовёт именно его", () => {
    expect(typeof refreshRoute.POST).toBe("function");
  });

  it("других state-changing методов роут не экспортирует", () => {
    for (const method of ["PUT", "PATCH", "DELETE", "HEAD"]) {
      expect(method in refreshRoute).toBe(false);
    }
  });
});
