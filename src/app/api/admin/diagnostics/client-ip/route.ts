import { ok } from "@/lib/api/response";
import { requireAdminAuth } from "@/lib/auth/admin";
import { resolveClientIpDiagnostics } from "@/lib/http/ip";

/**
 * FIX-B17 — «проверить наблюдением» → «спросить одним запросом».
 *
 * `TRUSTED_PROXY_HOPS` решает, какая запись цепочки `X-Forwarded-For` считается
 * клиентом. Неверное значение не даёт ни ошибки, ни лога, ни красного теста —
 * оно молча превращает КАЖДЫЙ per-IP лимит продукта либо в глобальный (хопов
 * меньше реальности: всё схлопывается в адрес edge'а), либо в обходимый (хопов
 * больше: потребляется запись, которую подставил сам клиент). Проверить это
 * можно только против настоящего деплоя, поэтому инструмент нужен ДО закрытого
 * деплоя, а не после первого инцидента.
 *
 * 🔴 Почему отдельный роут, а не поле в существующей админской поверхности.
 * Ответ здесь **request-scoped по своей природе**: он описывает ИМЕННО этот
 * запрос. `admin/dashboard/health` и `admin/system-config` отвечают про
 * состояние системы, их ответы кэшируются и потребляются формами — диагностика
 * конкретного запроса внутри них читалась бы как свойство системы и врала бы
 * при первом же кэше.
 *
 * 🔴 Эхо ограничено ТРЕМЯ заголовками, относящимися к разрешению адреса.
 * Роут, отражающий произвольные заголовки, — это готовый вынос куки и
 * `Authorization` любому, кто дотянется; сужение до трёх имён делает
 * безопасность свойством кода, а не свойством авторизации. Авторизация при
 * этом тоже стоит: `requireAdminAuth` (роль + живая сессия), а частотный лимит
 * приходит тиром прокси (`publicApi`) — как у любого `/api/*`.
 *
 * ⚠️ Роут намеренно НЕ внесён в `SENSITIVE_ROUTE_PREFIXES`: fail-closed здесь
 * значил бы, что при обрыве Redis диагностика недоступна ровно тогда, когда
 * ею идут разбираться. Читающий роут без побочных эффектов, инв. #6 про него
 * не говорит.
 */
export const dynamic = "force-dynamic";

export async function GET(req: Request) {
  const auth = await requireAdminAuth();
  if (!auth.ok) return auth.response;

  return ok(resolveClientIpDiagnostics(req));
}
