/**
 * UI-11 — единственный источник решения «плавно или мгновенно».
 *
 * Гейт `prefers-reduced-motion` у прокрутки живёт в ДВУХ независимых
 * механизмах, и закрыть надо оба, потому что один другого не покрывает:
 *
 *  • CSS-свойство `scroll-behavior` (`globals.css`) действует на якорные
 *    переходы и на вызовы БЕЗ явного `behavior` — там подставляется `auto`,
 *    а `auto` означает «спросить у CSS»;
 *  • явный `behavior: "smooth"` в `scrollTo`/`scrollIntoView` перекрывает
 *    CSS по спецификации CSSOM-View. То есть медиазапрос, добавленный в
 *    таблицу стилей, на такие вызовы НЕ распространяется вовсе — а именно
 *    ими сделаны программные прокрутки продукта (каталог «наверх», лента
 *    чата, шаги визарда, колонка дня в расписании).
 *
 * Проверка идёт в момент прокрутки, а не при монтировании: пользователь
 * может переключить системную настройку с открытой вкладкой.
 *
 * Сторож — `scroll.test.ts`: литерал `behavior: "smooth"` вне этого модуля
 * валит CI, иначе следующий программный скролл снова окажется негейченным
 * и это будет невидимо (у вестибулярно чувствительного пользователя нет
 * способа сообщить нам, что его укачало).
 */

/** Просил ли пользователь ограничить движение. Безопасно вне браузера. */
export function prefersReducedMotion(): boolean {
  return (
    typeof window !== "undefined" &&
    typeof window.matchMedia === "function" &&
    window.matchMedia("(prefers-reduced-motion: reduce)").matches
  );
}

/**
 * Значение для `behavior` у `scrollTo` / `scrollIntoView`.
 * `"auto"` здесь — мгновенный переход, а не «как решит CSS»: при
 * ограничении движения именно этого и надо.
 */
export function scrollBehavior(): ScrollBehavior {
  return prefersReducedMotion() ? "auto" : "smooth";
}
