import * as cache from "@/lib/cache/cache";

/**
 * FIX-C11 — сторож «это уведомление уже отправляли», и его поведение при
 * недоступной зависимости названо ЯВНО.
 *
 * ## Почему модуль появился
 *
 * Три сайта (`weekly-stats-job` — сторож прогона и сторож на мастера,
 * `hot-slots/slot-freed` — анти-спам на пару «пользователь × кабинет») звали
 * `cache.setNx` **без обработки отказа вовсе**. Отказ при обрыве Redis уходил
 * наружу как исключение, и это работало «правильно» СЛУЧАЙНО: политики не было
 * ни в коде, ни в комментарии — был пропуск, который никто не выбирал.
 *
 * Пропуск и решение различаются ровно в тот момент, когда кто-то захочет
 * поменять поведение: у решения есть причина, у пропуска — нет, поэтому его
 * меняют не думая.
 *
 * ## Выбранная семантика: fail-CLOSED (не рассылать) — РАТИФИЦИРОВАНО FIX-C12
 *
 * FIX-C11 выбрал fail-closed как «сохранить то, что было, и назвать это», и
 * честно пометил решение нератифицированным. FIX-C12 установил решающий факт —
 * **оба потребителя ретраятся**, — и на нём решение закрыто:
 *
 *   · `slot.freed` — задача очереди. `worker.ts:663-684`: бросок обработчика
 *     ловится, задача возвращается в очередь с задержкой `60_000 × попытка` до
 *     `WORKER_RETRY_MAX_ATTEMPTS`, затем dead-letter. Пропуск восстанавливается
 *     сам, провал остаётся видимым.
 *   · `weekly-stats` — периодический вызов `setInterval` раз в ЧАС
 *     (`worker.ts:264-271`), срабатывающий только в понедельник UTC. То есть у
 *     прогона ~24 попытки за понедельник — при условии, что сторож прогона снят
 *     (внешний `catch` в `runWeeklyStatsJob` снимает `runGuardKey`; ради этого
 *     FIX-C12 и пробрасывает `NotificationDedupUnavailableError` из
 *     per-master-цикла, см. комментарий там).
 *
 * Раз пропуск восстанавливается ретраем, а дубликат — нет, размен
 * односторонний: дубликат здесь **виден пользователю** («ваша статистика за
 * неделю», push о освободившемся слоте) и неотзываем, а пропущенный прогон
 * повторится сам. Отдельно взвешивать `slot.freed` (пропуск = потерянная
 * бронь, то есть смысл продукта) не требуется именно потому, что он ретраится:
 * уведомление не теряется, оно откладывается на минуту.
 *
 * 🚨 Менять семантику — только вместе с этим блоком И с проверкой, что оба
 * потребителя всё ещё ретраятся: именно ретрай делает размен односторонним.
 * Инвентарь потребителей и их ретраев пиннится `dedup-guard.test.ts`.
 */

/** Отказ сторожа: посчитать «первый ли это раз» не удалось. */
export class NotificationDedupUnavailableError extends Error {
  constructor(key: string, cause: unknown) {
    super(
      `Notification dedup guard unavailable for key=${key}: ` +
        (cause instanceof Error ? cause.message : String(cause))
    );
    this.name = "NotificationDedupUnavailableError";
  }
}

/**
 * `true` — этот ключ виден ВПЕРВЫЕ, отправлять можно.
 * `false` — уже отправляли в пределах TTL, пропустить.
 * Бросает `NotificationDedupUnavailableError` — посчитать не удалось, НЕ отправлять.
 */
export async function claimNotificationDedup(
  key: string,
  ttlSeconds: number
): Promise<boolean> {
  const claim = await cache.claimLock(key, "1", ttlSeconds);
  if (claim.status === "unavailable") {
    throw new NotificationDedupUnavailableError(key, claim.error);
  }
  return claim.status === "acquired";
}
