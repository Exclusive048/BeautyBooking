import type { Sharp } from "sharp";

/**
 * PERF-07 — верхняя граница разрешения загруженного изображения.
 *
 * Перекодирование на аплоаде было (sharp re-encode, SEC-06), а `.resize()` —
 * нет ни в одном из пяти путей загрузки: в хранилище ложился оригинал вплоть
 * до `MEDIA_MAX_FILE_SIZE_BYTES` (10 МБ). Следствия разные и их надо
 * различать:
 *
 *  - **Портфолио и аватары** идут через `next/image`, поэтому браузер получает
 *    ресайз — но оптимизатор Next при КАЖДОМ промахе своего кэша скачивает
 *    десятимегабайтный оригинал из S3 и жмёт его на CPU app-сервера, по разу
 *    на каждую комбинацию (ширина × качество × формат).
 *  - **Вложения чата** рендерятся обычным `<img>` осознанно (роут отдачи
 *    держит cookie-auth + токен, а `next/image` переписал бы URL через свой
 *    пайплайн и потерял токен), то есть оригинал едет прямо в браузер — в бокс
 *    высотой 200 px.
 *
 * Пороги выведены из самой крупной поверхности показа, а не взяты на глаз.
 * Портфолио: самый широкий `sizes` в продукте — `(max-width: 768px) 100vw,
 * 480px` (`stories-viewer-overlay.tsx`), то есть максимум физических пикселей
 * = 768 × 3 DPR = 2304; 2560 покрывает это с запасом и при этом `next/image`
 * никогда не отдаст больше, чем есть в источнике. Вложения и референсы живут в
 * пузыре чата / карточке брони (≲500 CSS px), 1600 покрывает 3×.
 *
 * `withoutEnlargement` обязателен: без него мелкая картинка растянулась бы до
 * порога — это и вес, и потеря качества. `fit: "inside"` ограничивает ДЛИННУЮ
 * сторону независимо от ориентации. Обе настройки — причина, по которой это
 * одна функция, а не четыре одинаковых вызова: разойтись им нельзя.
 *
 * Что НЕ делается здесь: `.rotate()` (применение EXIF-ориентации). sharp
 * метаданные при переупаковке снимает и сам не поворачивает, поэтому снимок с
 * телефона и сегодня хранится «как есть» — это существующий дефект
 * ориентации, а не следствие ресайза, и он заведён отдельно
 * (`MEDIA-EXIF-ORIENTATION` в BACKLOG). Молча поменять ориентацию уже
 * работающих загрузок — не задача перф-фикса.
 */
export const MEDIA_MAX_IMAGE_SIDE_PX = 2560;

/** Вложения чата и референсы брони — см. вывод порогов выше. */
export const MEDIA_ATTACHMENT_MAX_IMAGE_SIDE_PX = 1600;

export function capLongestSide(pipeline: Sharp, maxSidePx: number): Sharp {
  return pipeline.resize({
    width: maxSidePx,
    height: maxSidePx,
    fit: "inside",
    withoutEnlargement: true,
  });
}
