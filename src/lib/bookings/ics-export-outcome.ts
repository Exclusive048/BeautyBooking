/**
 * FIX-B18 · ICS-NAVIGATION-ENVELOPE — исходы выгрузки брони в календарь.
 *
 * Client-safe модуль (CLAUDE.md rule 13): его импортирует и роут, и страница
 * «Мои записи». Смысл общего союза типов тот же, что у `OAuthStartFailure`
 * (FIX-B14): маппинг исхода в текст живёт в UI и опирается на этот тип,
 * поэтому новый исход без строки не проедет мимо `typecheck`.
 *
 * ## Почему это отдельный класс от auth-стартов
 *
 * `GET /api/bookings/[id]/ics` — не «эндпоинт API»: сюда ведёт `<a href>` из
 * списка записей, то есть исход попадает в браузер, которому надо где-то
 * оказаться. До этого фикса все пять отказов отдавали JSON-конверт — FIX-B14
 * привёл их тексты в порядок (машинные коды уехали), но форму не тронул,
 * потому что порог тогда стоял на auth-поверхностях.
 *
 * Назначение при этом ДРУГОЕ, чем у стартовой ноги OAuth. Там пользователь шёл
 * «войти» и `/login` — его цель. Здесь он шёл к СВОЕЙ записи, поэтому вернуть
 * его надо к записи: в список с `?focus=<id>` (тот же deep-link, что у
 * уведомлений и CTA), а при отсутствии сессии — на `/login?next=<туда же>`,
 * чтобы после входа он оказался там, куда шёл, а не на дефолтной странице.
 *
 * ## Почему у ссылки снят атрибут `download`
 *
 * `<a download>` заставляет браузер СКАЧАТЬ то, что вернулось, включая цель
 * редиректа: отказ приземлился бы файлом с HTML-страницей вместо перехода.
 * Атрибут при этом не нужен — успешный ответ несёт
 * `Content-Disposition: attachment`, и он один уже вызывает скачивание, не
 * уводя пользователя со страницы. То есть снятие `download` ничего не ломает
 * на успехе и чинит отказ.
 */
export type IcsExportFailure =
  /** Сессии нет — единственный исход, ведущий на `/login` (с `next`). */
  | "auth_required"
  /** Записи с таким id не существует. */
  | "not_found"
  /** Запись существует, но принадлежит другому пользователю. */
  | "forbidden"
  /** У записи нет времени — выгружать в календарь нечего. */
  | "no_time"
  /** Внутренний сбой. */
  | "failed";

/** Ключ, которым исход едет в адресной строке (`?ics=<...>`). */
export const ICS_FAILURE_PARAM = "ics";

/**
 * Страница, на которую возвращается пользователь. Список записей, а не
 * конкретная бронь: отдельной страницы брони у клиента нет, подсветка строки
 * делается через `?focus=`.
 */
export const CLIENT_BOOKINGS_PATH = "/cabinet/bookings";

/** Куда вернуть браузер после отказа — общий вид для роута и для `?next=`. */
export function icsFailureReturnPath(bookingId: string): string {
  return `${CLIENT_BOOKINGS_PATH}?focus=${encodeURIComponent(bookingId)}`;
}
