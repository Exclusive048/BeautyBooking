/**
 * SLOTS-FLUSH-STARTS (2026-10-29) — `?after=<ISO>` у выдачи окошек: момент,
 * с которого визард пакета показывает время следующей услуги (конец предыдущей
 * + пауза мастера). Предыдущая услуга ещё не записана, поэтому день мастера о
 * ней не знает, и время «сразу после» неё без подсказки не появилось бы.
 * Выдача добавляет этот момент к началам ЕГО дня (`buildSlotsForDay.extraStartsUtc`),
 * проверяет как любое другое начало и кэширует этот день под своим ключом —
 * остальные дни запроса делят общий кэш.
 *
 * Неподходящее значение молча не учитывается — это подсказка, а не условие.
 * Запись пакета этому параметру не доверяет: время проверяет `resolveBookingCore`.
 */
export function resolveFlushAfterParam(raw: string | null): Date | null {
  if (!raw) return null;
  const value = new Date(raw);
  return Number.isNaN(value.getTime()) ? null : value;
}
