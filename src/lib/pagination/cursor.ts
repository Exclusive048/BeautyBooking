/**
 * Непрозрачный курсор пагинации (SEC-12).
 *
 * Rule 12 запрещает отдавать сырые внутренние CUID в публичных ответах, и
 * курсор — такой же публичный ответ, как любое другое поле. Правильная форма
 * уже существовала, но жила приватной функцией внутри `catalog.service.ts`,
 * поэтому соседние списки (`providers/queries.ts`, `/api/hot-slots`) отдавали
 * курсором сырой `id`. Аудит отметил это отдельно: задокументированное
 * исключение для `/api/providers/[id]` на курсор **не распространяется**.
 *
 * Кодирование не является защитой и секретом не притворяется: оно обратимо и
 * его задача — не пускать внутренние идентификаторы в публичную поверхность и
 * развязать публичный контракт со storage-id. От перечисления защищают
 * рейт-лимит (SEC-03) и проверки публикации (SEC-05, SEC-11).
 *
 * Чистая функция (только Buffer) — безопасна к импорту с любой стороны.
 */

/** Внутренний id → непрозрачный URL-safe токен курсора. */
export function encodeCursor(id: string): string {
  return Buffer.from(id, "utf-8").toString("base64url");
}

/** Токен курсора → внутренний id, либо null, если токен не разбирается. */
export function decodeCursor(cursor: string): string | null {
  try {
    const decoded = Buffer.from(cursor, "base64url").toString("utf-8");
    return decoded.length > 0 ? decoded : null;
  } catch {
    return null;
  }
}
