/**
 * Версия набора иконок в адресах — `?v=` у фавиконок, apple-touch-icon,
 * иконок манифеста, заставок iOS и картинок бренда (BRAND-ICONS-CACHE-01).
 *
 * Зачем: новый файл по ТОМУ ЖЕ адресу до пользователя не доезжает. Сервис-
 * воркер отдаёт картинки из `images-cache` (StaleWhileRevalidate — первый ответ
 * всегда из кэша), у Chrome свой кэш фавиконок, iOS держит apple-touch-icon и
 * заставки, а иконку приложения при установке браузер берёт из тех же кэшей.
 * Так набор «Наложение» (BRAND-ICONS-03) лежал на проде, а вкладка и
 * приложение на рабочем столе показывали прежнюю «M».
 *
 * Значение — отпечаток содержимого `public/brand/` и `public/splash/`
 * (`brand-asset-fingerprint.ts`). Его и адреса в манифесте переписывает
 * `npm run generate:icons`; файлы поменялись, а версия нет — красный
 * `brand-asset-version.test.ts`. Адрес самого манифеста не версионируется:
 * воркер его не кэширует (ответ `max-age=0`), а установленное приложение
 * узнаёт себя по `id`, и менять ему адрес манифеста незачем.
 */
export const BRAND_ASSET_VERSION = "76a1ca0e2e";

export function versionedBrandUrl(url: string): string {
  return `${url}?v=${BRAND_ASSET_VERSION}`;
}
