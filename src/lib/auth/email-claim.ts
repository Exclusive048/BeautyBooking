import type { Prisma, PrismaClient } from "@prisma/client";

/**
 * EMAIL-ADDRESS-OCCUPATION — семантика освобождения адреса.
 *
 * Модель владения после перехода на частичный уникальный индекс
 * (`WHERE "emailVerifiedAt" IS NOT NULL`; индекс создаётся в объединённом
 * baseline `20260324190000_init_squashed`, исходно —
 * `20260812104330_email_partial_unique_verified_only`, MIGRATION-SQUASH-01):
 *
 *   ЗАЯВИТЬ адрес может кто угодно и сколько угодно профилей — это просто
 *   строка без доказательства. ВЛАДЕТЬ им может ровно один, и владение даёт
 *   только успешно введённый код.
 *
 * Отсюда правило, которое иначе забывается: **в момент, когда владелец
 * доказал владение, чужие НЕподтверждённые заявки на этот адрес обязаны
 * освободиться.** Без этого они остаются висеть и продолжают получать
 * сервисную почту (см. `notifications/delivery.ts`), а сам держатель видит в
 * профиле адрес, который ему уже не принадлежит.
 *
 * Что освобождение НЕ делает — и это тоже часть контракта:
 *  - не удаляет и не блокирует профиль держателя;
 *  - не трогает его сессии (он не разлогинивается);
 *  - не трогает его остальные каналы входа (телефон, VK, Yandex-линк);
 *  - не трогает `emailVerifiedAt` — освобождаются ТОЛЬКО строки, где он уже
 *    `null`, то есть где доказательства и не было.
 *
 * Держатель после освобождения теряет ровно то, чего у него никогда не было:
 * непроверенную запись чужого адреса.
 */

type DbClient = PrismaClient | Prisma.TransactionClient;

/**
 * Снимает НЕподтверждённые заявки на адрес со всех профилей, кроме указанного.
 *
 * ⚠️ Условие `emailVerifiedAt: null` в `where` — не оптимизация, а граница
 * безопасности: без него вызов стирал бы адрес у профиля, который им
 * доказанно владеет. Индекс не даст появиться двум подтверждённым строкам, но
 * primitive обязан быть безопасен и сам по себе — его будут звать новые пути.
 *
 * @param exceptUserId профиль, который как раз доказывает владение (при
 *   создании нового профиля его ещё нет — тогда `null`).
 * @returns сколько заявок освобождено (для лога; ноль — норма).
 */
export async function releaseUnverifiedEmailClaims(
  db: DbClient,
  normalizedEmail: string,
  exceptUserId: string | null,
): Promise<number> {
  const result = await db.userProfile.updateMany({
    where: {
      email: normalizedEmail,
      emailVerifiedAt: null,
      ...(exceptUserId ? { id: { not: exceptUserId } } : {}),
    },
    data: { email: null },
  });
  return result.count;
}
