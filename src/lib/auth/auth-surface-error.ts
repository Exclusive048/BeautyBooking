import { AppError, toAppError, type ErrorCode } from "@/lib/api/errors";

/**
 * FIX-C6 · SECURITY-EXPOSURE-AUDIT-01 · Y9 — у auth-границы нет поля `details`,
 * которое можно было бы прокинуть наружу.
 *
 * ## Что заменяется
 *
 * Y9 требует: ни один ответ auth-поверхности не несёт `AppError.details`
 * (провайдерские библиотеки кладут туда сырой ответ OAuth). Держал это регексп
 * `DETAILS_FORWARD` по строкам файла — то есть проверка СОДЕРЖИМОГО вызова, а
 * такая обходится сборкой аргумента заранее:
 *
 *     const payload = appError.details;
 *     return jsonFail(status, message, code, payload);   // детектору не видно
 *
 * Правило нельзя было перевести на признак «импортирует конверт»: `jsonFail`
 * законно импортируют почти все роуты, и он не отделяет нарушителя ни от кого.
 * Зато переводится ДРУГАЯ половина: убрать поле из того, что auth-поверхность
 * вообще держит в руках. Прокинуть отсутствующее свойство нельзя ни прямо, ни
 * через промежуточную переменную, ни спредом (`{ ...view }` тоже пуст на этот
 * счёт) — компилятор отвечает «Property 'details' does not exist».
 *
 * ## Почему тип, а не «ещё один хелпер-конверт»
 *
 * Хелпер `failAuthSurface(error)`, собирающий ответ целиком, закрыл бы только
 * тот путь, по которому его позвали. Здесь же меняется ВИД значения: в catch'е
 * auth-поверхности больше нет объекта с диагностикой, поэтому и утечь нечему
 * — независимо от того, каким конвертом роут в итоге отвечает.
 *
 * ## Граница честности
 *
 * Тип покрывает поверхности, которые ловят ошибку и отвечают на неё. Три
 * OAuth-колбэка держат `AppError` по другой причине — они его БРОСАЮТ
 * (`throw new AppError(...)`), — и их отказы идут через `failOAuthCallback`
 * (свой сторож). За ними остаётся `auth-surface-details.test.ts`, у которого в
 * шапке записано, что именно он теперь стережёт.
 */

/**
 * Вид ошибки для auth-поверхности: ровно то, что уезжает клиенту, и ничего
 * больше. Поля `details` тут нет намеренно и оно не должно появиться —
 * иначе правило Y9 вернётся в разряд «проверяется регекспом».
 */
export type AuthSurfaceError = {
  readonly message: string;
  readonly status: number;
  readonly code: ErrorCode;
};

/**
 * Сужает пойманную ошибку до вида, безопасного для ответа auth-границы.
 *
 * Диагностика не теряется — она уезжает в лог у вызывающего (`logError` со
 * стеком) либо через `logOAuthStartFailure` / `failOAuthCallback` со скрабом.
 * Теряется только возможность положить её в тело ответа.
 */
export function toAuthSurfaceError(error: unknown): AuthSurfaceError {
  const appError = error instanceof AppError ? error : toAppError(error);
  return { message: appError.message, status: appError.status, code: appError.code };
}
