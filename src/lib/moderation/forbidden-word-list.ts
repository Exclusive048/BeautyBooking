/**
 * FORBIDDEN-WORDS-01 (решение владельца 2026-10-01) — словарь запрещённого
 * в публичных текстах: имена и названия кабинетов, услуги и категории, пакеты,
 * описания, подписи к работам, отзывы и ответы, модель-офферы, адрес страницы.
 *
 * Правила записи — по СЛОВУ после нормализации (`forbidden-words.ts`), а не по
 * подстроке всего текста: подстрока даёт ложные срабатывания («оскорБЛЯть»,
 * «хлЕБА», «ПЕДИКюр», «неБАНальный»). Поэтому у каждого корня — форма:
 *
 *  · `anywhere` — корень внутри слова; только для корней, которых нет ни в одном
 *    обычном слове («пизд», «залуп»);
 *  · `start`    — слово начинается с корня, возможно после приставки из
 *    `prefixes` («похуй», «заебал»);
 *  · `exact`    — слово целиком из списка форм («сука», «педик» — но не
 *    «сукно», «педикюр»).
 *
 * `except` — обычные слова, которые формально подходят под правило («хулиган»
 * у «ху…» не подходит и так, а «херсон» у «хер» — подходит). Новый корень
 * добавляется вместе со строкой ложного срабатывания в
 * `forbidden-words.test.ts` — она и есть доказательство, что правило не
 * съест обычное слово.
 */

export type ForbiddenCategory =
  /** Мат и его производные. */
  | "obscene"
  /** Оскорбления людей. */
  | "insult"
  /** Ненависть по национальности, призывы и символика экстремизма. */
  | "hate"
  /** Наркотики. */
  | "drugs"
  /** Секс-услуги и порнография (не интимная депиляция — это обычная услуга). */
  | "sexual"
  /** Выдача себя за платформу — только в именах и адресе страницы. */
  | "impersonation";

export type ForbiddenRule = {
  category: ForbiddenCategory;
  /** Корни в нормализованной форме: нижний регистр, «ё» → «е», без повторов букв. */
  roots: readonly string[];
  match: "anywhere" | "start" | "exact";
  /** Для `start`: приставки, после которых корень тоже считается началом слова. */
  prefixes?: readonly string[];
  /** Обычные слова, которые правило не трогает (нормализованная форма). */
  except?: readonly string[];
};

