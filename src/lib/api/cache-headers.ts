/**
 * PERF-13 — заголовки кэширования для публичных ответов API.
 *
 * До этого `Cache-Control` в `src/` встречался 9 раз, и публично-кэшируемым был
 * ровно один (`/api/cities`): `ok()` заголовок не ставит, глобальный `headers()`
 * в `next.config.ts` — только security. То есть справочники, одинаковые для всех
 * и меняющиеся раз в недели, пересчитывались на каждый запрос.
 *
 * 🔴 Почему `public` нельзя ставить бездумно — и почему рядом стоит вторая
 * половина фикса в `src/proxy.ts`. Прокси при протухшем access-токене обновляет
 * сессию и **дописывает `Set-Cookie` в ответ ЛЮБОГО совпавшего пути**
 * (`proxy.ts`, ветка `refreshedSetCookies`), включая эти самые справочники.
 * Ответ с `public, s-maxage=…` И сессионной кукой, попавший в разделяемый кэш, —
 * это выдача чужой сессии следующему посетителю. Большинство CDN такие ответы не
 * кэшируют по умолчанию, но ровно так же «по умолчанию» держался CORS до SEC-19:
 * защита жила в чужой конфигурации, а не в коде.
 *
 * ⚠️ Очевидное решение — «прокси понижает директиву до `private, no-store`, когда
 * прикладывает куку» — **не работает, проверено рантаймом**: заголовок, который
 * ставит обработчик роута, ВЫИГРЫВАЕТ у заголовка middleware (curl на
 * `/api/reviews/tags` с безусловным понижением в прокси вернул всё тот же
 * `public, …`). Юнит-тест этого не ловит — он видит собственный `NextResponse`
 * прокси, а не итоговый смерженный ответ. Поэтому граница проведена структурно:
 * `PUBLIC_REFERENCE_API_PATHS` ниже — ОДИН список с двумя потребителями, и на
 * этих путях прокси не делает refresh-хоп вовсе. Множества «ответ кэшируем
 * разделяемым кэшем» и «ответ несёт сессионную куку» не пересекаются
 * по построению, а не по договорённости.
 *
 * Пропуск обновления на них безобиден: ни один из этих роутов не читает сессию,
 * а обновление произойдёт на следующем же запросе к любому другому пути.
 *
 * Ставить этот заголовок можно ТОЛЬКО там, где тело ответа не зависит ни от
 * сессии, ни от роли, ни от заголовков — то есть ответ анониму и админу
 * побайтово одинаков. Всё, что зависит от зрителя (слоты, `/api/me/*`, кабинеты),
 * остаётся без заголовка либо `private`. И новый такой роут обязан появиться в
 * `PUBLIC_REFERENCE_API_PATHS`, иначе прокси приложит к нему куку.
 */

/**
 * Справочники: `max-age` браузера намеренно мал (дедупликация внутри сессии,
 * пользователю невидима), основная экономия — `s-maxage` в разделяемом кэше;
 * `stale-while-revalidate` не даёт холодному кэшу задерживать ответ.
 */
export const PUBLIC_REFERENCE_CACHE_CONTROL =
  "public, max-age=60, s-maxage=300, stale-while-revalidate=600";

/**
 * Пути, чей ответ объявлен `PUBLIC_REFERENCE_CACHE_CONTROL`. Два потребителя
 * одного списка: сами роуты (через `publicReferenceCacheInit`) и `src/proxy.ts`,
 * который на этих путях не делает refresh-хоп и, значит, не может приложить
 * сессионную куку к разделяемо-кэшируемому ответу. Список пиннится тестом
 * `cache-headers.test.ts` — он же не даст ему разойтись с роутами.
 */
export const PUBLIC_REFERENCE_API_PATHS = [
  "/api/catalog/global-categories",
  "/api/home/tags",
  "/api/reviews/tags",
  "/api/billing/plans",
  "/api/cities",
  // MOBILE-AUTH-A: конфиг нативного приложения (версии, методы входа, фичи) —
  // от зрителя не зависит.
  "/api/mobile/v1/config",
] as const;

/** Совпадение точное: ни у одного пути списка нет динамических сегментов. */
export function isPublicReferenceApiPath(pathname: string): boolean {
  return (PUBLIC_REFERENCE_API_PATHS as readonly string[]).includes(pathname);
}

/** Готовые заголовки для `ok(data, publicReferenceCacheInit())`. */
export function publicReferenceCacheInit(): ResponseInit {
  return { headers: { "Cache-Control": PUBLIC_REFERENCE_CACHE_CONTROL } };
}

/**
 * PUBLIC-CACHE-SET-COOKIE — `public`-ответы ВНЕ списка выше.
 *
 * Три роута (медиа-файл, его вырез, OG-картинка) объявляют разделяемый кэш, но
 * из-под обновления сессии их вывести нельзя: медиа читает сессию на приватной
 * ветке, и пропуск обновления ломал бы приватные вложения при протухшем
 * access-токене. С SESSION-REFRESH-PATH-01 (`bh_refresh` на `Path=/`) прокси
 * действительно ротирует сессию и на этих путях — и дописывает `Set-Cookie` к
 * ответу, который сам объявил себя `public`.
 *
 * Понизить директиву из прокси нельзя (заголовок обработчика выигрывает, см.
 * шапку). Поэтому решение принимает обработчик — единственное место, где
 * известны ОБА факта: прокси сообщает заголовком ЗАПРОСА, что в ответ этого
 * запроса уйдёт обновлённая кука, а обработчик тогда отдаёт `private, no-store`.
 * Цена — один некэшируемый ответ раз в два часа на пользователя. Заголовок,
 * присланный клиентом, прокси снимает; подделка всё равно могла бы только
 * отключить кэш у самого подделавшего.
 */
export const SESSION_REFRESHED_REQUEST_HEADER = "x-mr-session-refreshed";

/** Директива для `public`-ответа вне `PUBLIC_REFERENCE_API_PATHS`. */
export function sharedCacheControlFor(req: Request, cacheControl: string): string {
  return req.headers.get(SESSION_REFRESHED_REQUEST_HEADER) === "1" ? "private, no-store" : cacheControl;
}
