import { describe, expect, it } from "vitest";
import { timezoneForRegions } from "./region-timezone";

/**
 * Пояс нового города по субъекту РФ из ответа геокодера.
 *
 * @probe 2026-09-29 — «сахалинск» поставлен после «саха»: покраснел «Сахалин —
 * не Якутия» (получено Asia/Yakutsk). Возвращено — зелёный.
 * @probe 2026-09-29 — сравнение по подстроке (`includes`) вместо начала слова:
 * покраснел «Томская — не Омск» (получено Asia/Omsk). Возвращено — зелёный.
 */

// Как отдаёт геокодер: федеральный округ, затем субъект (оба `province`).
const tz = (...regions: string[]) => timezoneForRegions(regions);

describe("пояс нового города по субъекту РФ", () => {
  it("субъекты не в UTC+3", () => {
    expect(tz("Приволжский федеральный округ", "Самарская область")).toBe("Europe/Samara");
    expect(tz("Уральский федеральный округ", "Свердловская область")).toBe("Asia/Yekaterinburg");
    expect(tz("Дальневосточный федеральный округ", "Хабаровский край")).toBe("Asia/Vladivostok");
    expect(tz("Сибирский федеральный округ", "Новосибирская область")).toBe("Asia/Novosibirsk");
    expect(tz("Северо-Западный федеральный округ", "Калининградская область")).toBe("Europe/Kaliningrad");
    expect(tz("Уральский федеральный округ", "Ханты-Мансийский автономный округ — Югра")).toBe("Asia/Yekaterinburg");
    expect(tz("Уральский федеральный округ", "Ямало-Ненецкий автономный округ")).toBe("Asia/Yekaterinburg");
    expect(tz("Сибирский федеральный округ", "Кемеровская область — Кузбасс")).toBe("Asia/Novokuznetsk");
    expect(tz("Дальневосточный федеральный округ", "Чукотский автономный округ")).toBe("Asia/Anadyr");
  });

  it("Томская — не Омск, Омская — Омск", () => {
    expect(tz("Сибирский федеральный округ", "Томская область")).toBe("Asia/Tomsk");
    expect(tz("Сибирский федеральный округ", "Омская область")).toBe("Asia/Omsk");
  });

  it("Сахалин — не Якутия", () => {
    expect(tz("Дальневосточный федеральный округ", "Сахалинская область")).toBe("Asia/Sakhalin");
    expect(tz("Дальневосточный федеральный округ", "Республика Саха (Якутия)")).toBe("Asia/Yakutsk");
  });

  it("UTC+3 без своего пояса — по умолчанию (null)", () => {
    expect(tz("Центральный федеральный округ", "Москва")).toBeNull();
    expect(tz("Приволжский федеральный округ", "Республика Татарстан")).toBeNull();
    expect(tz("Северо-Западный федеральный округ", "Ненецкий автономный округ")).toBeNull();
    expect(tz()).toBeNull();
  });

  it("свой пояс с UTC+3: Волгоград, Киров, Крым", () => {
    expect(tz("Южный федеральный округ", "Волгоградская область")).toBe("Europe/Volgograd");
    expect(tz("Приволжский федеральный округ", "Кировская область")).toBe("Europe/Kirov");
    expect(tz("Южный федеральный округ", "Республика Крым")).toBe("Europe/Simferopol");
  });
});
