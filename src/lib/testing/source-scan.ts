/**
 * FIX-C5 — общая машинерия сторожей: убрать комментарии, НЕ убрав код.
 *
 * ## Что было сломано
 *
 * Ходовой в проекте шаблон `source.replace(/^[^\n]*?\/\/.*$/gm, "")` удаляет
 * СТРОКУ ЦЕЛИКОМ, если в ней где-то есть `//`. То есть код с хвостовым
 * комментарием исчезает вместе с комментарием:
 *
 *     if (res.ok) return; // гонка: байты доехали
 *     ↓ после «очистки»
 *     (пусто)
 *
 * Поймано пробой в FIX-C3: сторож покраснел на защите, которая существует.
 * Ложный красный — везучая сторона. Опасная — **ложный зелёный**: если удалённая
 * строка содержала то, что сторож ищет, он объявит «нарушений нет». А хвостовой
 * комментарий рядом с подозрительной строкой — это не экзотика, а норма: именно
 * там авторы объясняют, почему написали так.
 *
 * Инвентарь на 2026-08-13: форму использовали **4** guard-файла, и все четыре
 * ищут однострочные конструкции, у которых хвостовой комментарий правдоподобен.
 *
 * ## Почему не `^\s*\/\/`
 *
 * Он безопасен (сносит только строки-комментарии целиком) и потому годится как
 * заплатка, но неполон: хвостовой комментарий остаётся в тексте, и сторож,
 * ищущий, например, `\.details\b`, найдёт совпадение в ПРОЗЕ — то есть даст
 * ложный красный с другой стороны. Оба направления лечит одно: убирать ровно
 * комментарий и ровно его.
 *
 * ## Почему не полноценный парсер
 *
 * Избыточно. Достаточно маленького посимвольного сканера, знающего пять
 * состояний: строка `'`, строка `"`, шаблон (обратная кавычка), блочный
 * комментарий, строчный комментарий. Плюс регулярные литералы — их пропуск
 * обязателен, иначе регулярка, содержащая открывающую последовательность
 * блочного комментария, читалась бы как его начало и сканер съел бы остаток
 * файла (проверено тестом «регулярный литерал не читается как начало
 * комментария»).
 *
 * ⚠️ Примеры с последовательностями комментариев в этом файле намеренно
 * описаны словами, а не показаны дословно: закрывающая пара внутри JSDoc
 * обрывает сам JSDoc. Ровно на этом файл и не собрался при первой сборке —
 * документация о разборе комментариев сломала разбор комментариев.
 */

/** Может ли `/` в этой позиции начинать регулярный литерал, а не деление. */
function regexCanStartHere(prevSignificant: string): boolean {
  if (prevSignificant === "") return true;
  return "=(,:[!&|?{};+-*%^~<>".includes(prevSignificant);
}

/**
 * Удаляет комментарии, сохраняя код, переводы строк и содержимое строковых и
 * регулярных литералов. Позиции строк сохраняются (комментарий заменяется
 * пустотой, перевод строки остаётся), поэтому номера строк не съезжают.
 */
export function stripComments(source: string): string {
  let out = "";
  let i = 0;
  let prevSignificant = "";
  const n = source.length;

  while (i < n) {
    const ch = source[i]!;
    const next = source[i + 1];

    // --- комментарии ---
    if (ch === "/" && next === "/") {
      while (i < n && source[i] !== "\n") i += 1;
      continue; // сам `\n` попадёт в out на следующей итерации
    }
    if (ch === "/" && next === "*") {
      i += 2;
      while (i < n && !(source[i] === "*" && source[i + 1] === "/")) {
        // Переводы строк внутри блочного комментария сохраняем — иначе
        // съезжают номера строк, а сторожи их печатают.
        if (source[i] === "\n") out += "\n";
        i += 1;
      }
      i += 2;
      continue;
    }

    // --- строковые литералы ---
    if (ch === '"' || ch === "'" || ch === "`") {
      const quote = ch;
      out += ch;
      i += 1;
      while (i < n) {
        const c = source[i]!;
        if (c === "\\") {
          out += c + (source[i + 1] ?? "");
          i += 2;
          continue;
        }
        out += c;
        i += 1;
        if (c === quote) break;
      }
      prevSignificant = quote;
      continue;
    }

    // --- регулярные литералы ---
    if (ch === "/" && regexCanStartHere(prevSignificant)) {
      let j = i + 1;
      let inClass = false;
      let closed = false;
      while (j < n) {
        const c = source[j]!;
        if (c === "\\") {
          j += 2;
          continue;
        }
        if (c === "\n") break; // незакрытый — значит это было не регекспом
        if (c === "[") inClass = true;
        else if (c === "]") inClass = false;
        else if (c === "/" && !inClass) {
          closed = true;
          break;
        }
        j += 1;
      }
      if (closed) {
        out += source.slice(i, j + 1);
        i = j + 1;
        prevSignificant = "/";
        continue;
      }
    }

    out += ch;
    if (!/\s/.test(ch)) prevSignificant = ch;
    i += 1;
  }

  return out;
}
