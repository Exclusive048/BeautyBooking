import { readFileSync } from "node:fs";
import { join } from "node:path";

import { describe, expect, it } from "vitest";

import { UI_TEXT } from "@/lib/ui/text";

/**
 * FIX-C3 · item 3 — у отказа приватного вложения появилась ПРИЧИНА.
 *
 * ## Почему это отдельный класс от FIX-B14
 *
 * FIX-B14 чинил роуты, до которых доходят НАВИГАЦИЕЙ: там конверт-ошибка —
 * тупик, и лечится редиректом на страницу. Здесь роут отдаёт **байты** и
 * достигается только `<img src>`: JSON-конверт рендерится сломанной картинкой,
 * а у `onError` элемента `<img>` нет ни статуса, ни тела. «Доступа нет», «файла
 * нет» и «ссылка устарела» приходили в один и тот же обработчик неразличимыми.
 *
 * ## Что выбрано и почему не всё подряд
 *
 * Публичные картинки оставлены как есть: `ResilientImage` уже показывает
 * плейсхолдер, а различать там нечего — единственный реальный исход «файла
 * нет». Второй механизм ради одинакового результата был бы лишним кодом.
 *
 * Приватное вложение чата — другое дело: токен живёт 15 минут, поэтому на долго
 * открытой вкладке вложения перестают грузиться у пользователя, который **уже
 * вошёл**, и это состояние ДЕЙСТВЕННО (обновить страницу). Прежний ответ
 * маршрута говорил ему «Требуется вход в аккаунт» — то есть называл причиной
 * не то, ровно как F3.
 *
 * @probe   что сломать: (1) вернуть в маршруте строку «Требуется вход в
 *          аккаунт.» → «маршрут советует войти пользователю, который уже
 *          вошёл» — красный; (2) убрать `explainFailure` из `onError` →
 *          «отказ не выясняет причину» — красный.
 *          Оба восстановлены, `diff` с бэкапом пуст, зелено.
 */

const ROOT = process.cwd();
/**
 * Убираются блочные комментарии и строки, СОСТОЯЩИЕ из комментария. Хвостовой
 * `// …` после кода не трогается намеренно: первая версия использовала здесь
 * ходовой в проекте шаблон `^[^\n]*?\/\/.*$`, который сносит СТРОКУ ЦЕЛИКОМ, —
 * и `if (res.ok) return; // гонка…` исчезал вместе со своим кодом, из-за чего
 * сторож краснел на существующей защите. Поймано пробой, не ревью.
 */
const strip = (s: string) =>
  s.replace(/\/\*[\s\S]*?\*\//g, "").replace(/^\s*\/\/.*$/gm, "");

const route = strip(
  readFileSync(join(ROOT, "src/app/api/chat/attachment/[token]/route.ts"), "utf8"),
);
const bubble = strip(
  readFileSync(join(ROOT, "src/features/chat/chat-window/message-bubble.tsx"), "utf8"),
);

describe("FIX-C3 · маршрут называет причину, а не первое попавшееся", () => {
  it("протухший токен не советует «войти» уже вошедшему", () => {
    expect(
      /Требуется вход в аккаунт/.test(route),
      "маршрут советует войти пользователю, который уже вошёл: токен вложения " +
        "живёт 15 минут, и его истечение — самый частый отказ на этой поверхности",
    ).toBe(false);
    expect(route).toContain("attachmentLinkExpired");
  });

  it("строка отказа действенна — называет, что сделать", () => {
    // Предмет — содержание того, что прочитает человек, а не факт наличия ключа.
    expect(UI_TEXT.chat.composer.attachmentLinkExpired).toContain("Обновите страницу");
  });
});

describe("FIX-C3 · клиент различает состояния отказа", () => {
  it("на отказе картинки причина выясняется вторым запросом", () => {
    expect(
      /onError=\{\(\) => void explainFailure\(\)\}/.test(bubble),
      "отказ не выясняет причину — у `onError` у `<img>` нет ни статуса, ни тела, " +
        "поэтому без второго запроса все состояния остаются неразличимы",
    ).toBe(true);
  });

  it("сообщение сервера показывается пользователю, а не глотается", () => {
    expect(bubble).toMatch(/json\.error\?\.message/);
    expect(bubble).toMatch(/reason \?\? UI_TEXT\.chat\.composer\.attachmentLoadFailed/);
  });

  it("успешная загрузка второго запроса не делает", () => {
    // Цена механизма — один запрос на СБОЙНОЕ вложение; успешный путь не тронут.
    const onLoadLine = bubble.match(/onLoad=\{[^}]*\}/)?.[0] ?? "";
    expect(onLoadLine).not.toContain("explainFailure");
    expect(onLoadLine).toContain("setLoaded(true)");
  });

  it("гонка «байты доехали позже» не рисует ложную ошибку", () => {
    expect(bubble).toMatch(/if \(res\.ok\) return;/);
  });
});

describe("FIX-C3 · публичные картинки оставлены на существующем механизме", () => {
  it("ResilientImage существует и остаётся единственным плейсхолдером", () => {
    // Осознанное решение, а не пропуск: второй фолбэк-компонент не заводится.
    const resilient = readFileSync(join(ROOT, "src/components/ui/resilient-image.tsx"), "utf8");
    expect(resilient).toContain("onError={() => setErrored(true)}");
    expect(resilient).toMatch(/IMAGE_FALLBACK_SRC/);
  });
});
